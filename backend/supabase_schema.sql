-- Paste this script into Supabase SQL Editor and click Run

-- 1. Create products table
CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_number VARCHAR(100) NOT NULL,
  name VARCHAR(255) NOT NULL,
  slug VARCHAR(255),
  category VARCHAR(100) NOT NULL,
  price NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
  badge VARCHAR(50) DEFAULT '',
  primary_image TEXT NOT NULL,
  hover_image TEXT NOT NULL,
  description TEXT DEFAULT '',
  in_stock BOOLEAN DEFAULT TRUE,
  stock_quantity INTEGER DEFAULT 20,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Optional: Indexes for fast filtering & search
CREATE INDEX IF NOT EXISTS idx_products_category ON public.products(category);
CREATE INDEX IF NOT EXISTS idx_products_slug ON public.products(slug);
CREATE INDEX IF NOT EXISTS idx_products_item_number ON public.products(item_number);

-- 3. Enable Row Level Security (RLS)
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;

-- 4. Allow public read access to all products
CREATE POLICY "Allow public read access on products"
ON public.products
FOR SELECT
TO public
USING (true);

-- 5. Allow inserts/updates with anon/service key
CREATE POLICY "Allow write access on products"
ON public.products
FOR ALL
TO public
USING (true)
WITH CHECK (true);


-- 6. Users table with password_hash & verified status
CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) DEFAULT '',
  email VARCHAR(255) UNIQUE NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  is_verified BOOLEAN DEFAULT FALSE,
  phone VARCHAR(50) DEFAULT '',
  address TEXT DEFAULT '',
  city VARCHAR(100) DEFAULT '',
  postal_code VARCHAR(50) DEFAULT '',
  country VARCHAR(100) DEFAULT 'United States',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 7. OTP Verifications table (for email confirmation & password resets)
CREATE TABLE IF NOT EXISTS public.otp_verifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL,
  otp_hash VARCHAR(255) NOT NULL,
  type VARCHAR(50) DEFAULT 'signup', -- 'signup' or 'forgot_password'
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_otp_email ON public.otp_verifications(email);


-- 8. Ensure public.users has profile & address fields
ALTER TABLE public.users 
ADD COLUMN IF NOT EXISTS phone VARCHAR(50) DEFAULT '',
ADD COLUMN IF NOT EXISTS address TEXT DEFAULT '',
ADD COLUMN IF NOT EXISTS city VARCHAR(100) DEFAULT '',
ADD COLUMN IF NOT EXISTS state VARCHAR(50) DEFAULT '',
ADD COLUMN IF NOT EXISTS postal_code VARCHAR(50) DEFAULT '',
ADD COLUMN IF NOT EXISTS country VARCHAR(100) DEFAULT 'United States';

-- 9. Orders Table
CREATE TABLE IF NOT EXISTS public.orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_ref VARCHAR(50) UNIQUE NOT NULL, -- e.g. VL-948123
  user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  email VARCHAR(255) NOT NULL,
  items JSONB NOT NULL,                  -- array of { id, name, price, quantity, size, primaryImage }
  subtotal NUMERIC(10, 2) NOT NULL,
  shipping_fee NUMERIC(10, 2) DEFAULT 0.00,
  tax NUMERIC(10, 2) DEFAULT 0.00,
  total NUMERIC(10, 2) NOT NULL,
  payment_method VARCHAR(50) NOT NULL,   -- 'card', 'upi', 'cod'
  shipping_address JSONB NOT NULL,       -- { firstName, lastName, address, city, state, postalCode }
  status VARCHAR(50) DEFAULT 'confirmed',-- 'confirmed', 'processing', 'dispatched', 'delivered'
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- RLS policies for orders
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow public read and write on orders" ON public.orders FOR ALL TO public USING (true) WITH CHECK (true);
